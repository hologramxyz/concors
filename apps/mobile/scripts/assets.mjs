import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";
import sharp from "sharp";

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL("..", import.meta.url));
const assets = path.join(root, "assets");
await mkdir(assets, { recursive: true });
const source = await readFile(
  new URL("../../desktop/src-tauri/icons/source.svg", import.meta.url),
  "utf8",
);
const mark = source.replace(/<rect[^>]*\/>/, "");
await sharp(Buffer.from(source))
  .resize(1024, 1024)
  .flatten({ background: "#f4f3ef" })
  .png()
  .toFile(path.join(assets, "icon.png"));
await sharp(Buffer.from(mark))
  .resize(640, 640)
  .extend({ top: 192, bottom: 192, left: 192, right: 192, background: "#00000000" })
  .png()
  .toFile(path.join(assets, "adaptive-icon.png"));
await sharp(Buffer.from(mark.replace('color="#20211f"', 'color="#ffffff"')))
  .resize(96, 96)
  .png()
  .toFile(path.join(assets, "notification-icon.png"));
await sharp(Buffer.from(mark)).resize(512, 512).png().toFile(path.join(assets, "splash.png"));

const xterm = await readFile(require.resolve("@xterm/xterm"), "utf8");
const fit = await readFile(require.resolve("@xterm/addon-fit"), "utf8");
const css = await readFile(
  path.join(path.dirname(require.resolve("@xterm/xterm")), "../css/xterm.css"),
  "utf8",
);
const bridge = await readFile(new URL("./terminal-document.js", import.meta.url), "utf8");
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'none'; img-src data:"><style>${css}\nhtml,body,#terminal{margin:0;width:100%;height:100%;background:#151714}body{padding:8px;box-sizing:border-box}.xterm{height:100%}</style></head><body><div id="terminal"></div><script>${[xterm, fit, bridge].join("\n;").replaceAll("</script", "<\\/script")}</script></body></html>`;
await writeFile(
  path.join(assets, "terminal-html.ts"),
  `// Generated by scripts/assets.mjs.\nexport const terminalHtml = ${JSON.stringify(html)};\n`,
);
