import type {
  LayoutNode,
  WorkspaceOperation,
  WorkspaceProject,
  WorkspaceTab,
} from "@concors/protocol";

/**
 * Where a pane can go besides its own tab, and the one command that takes it there: into another
 * tab, of this workspace or another, or out into a tab of its own. Dragging a pane header onto the
 * sidebar, dragging a chat's row onto another row, and the pane menu all decide here, so they
 * agree on what may move. Terminals stay in their workspace, which owns their session; a chat with
 * a schedule stays too, as the schedule is tied to its chat's workspace.
 */
export interface PaneTransferTarget {
  projectId: string;
  /** The tab it joins; without one it gets a new tab in that workspace. */
  tabId?: string | undefined;
}

export function paneTransfer(
  source: {
    project: Pick<WorkspaceProject, "id" | "version">;
    tab: Pick<WorkspaceTab, "id" | "root">;
    pane: Extract<LayoutNode, { kind: "pane" }>;
  },
  target: PaneTransferTarget,
  options: {
    /** The daemon moves panes between workspaces and into new tabs (`pane-transfer-workspace`). */
    acrossWorkspaces: boolean;
    scheduled: boolean;
    /** Generated by the caller, so a previewed move and the one sent are the same. */
    ids: { splitId: string; tabId: string };
  },
): WorkspaceOperation | null {
  const { project, tab, pane } = source;
  const crossing = target.projectId !== project.id;
  if (target.tabId === tab.id) return null;
  if ((crossing || !target.tabId) && !options.acrossWorkspaces) return null;
  if (crossing && (pane.profile !== "chat" || options.scheduled)) return null;
  // A pane alone in its tab already has a tab of its own here.
  if (!crossing && !target.tabId && tab.root === pane.id) return null;
  return {
    kind: "pane.transfer",
    projectId: project.id,
    expectedVersion: project.version,
    tabId: tab.id,
    paneId: pane.id,
    targetTabId: target.tabId ?? options.ids.tabId,
    splitId: options.ids.splitId,
    ...(crossing ? { targetProjectId: target.projectId } : {}),
    ...(target.tabId ? {} : { newTab: true }),
  };
}

/**
 * The sidebar entry under the pointer while a pane is dragged: a tab's row joins that tab, the
 * rest of a workspace's entry (its own row, or the space around its tabs) opens a new tab there.
 * Returns the element to highlight with it.
 */
export function sidebarTransferTarget(
  under: Element | null,
): { target: PaneTransferTarget; element: HTMLElement } | null {
  const workspace = under?.closest<HTMLElement>("[data-drop-workspace]");
  const projectId = workspace?.dataset["dropWorkspace"];
  if (!under || !workspace || !projectId) return null;
  const row = under.closest<HTMLElement>("[data-drop-tab]");
  const tabId = row?.dataset["dropTab"];
  if (row && tabId) return { target: { projectId, tabId }, element: row };
  const header = document.querySelector<HTMLElement>(
    `[data-workspace-row="${CSS.escape(projectId)}"]`,
  );
  return { target: { projectId }, element: header ?? workspace };
}
